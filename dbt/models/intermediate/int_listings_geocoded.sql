SELECT
    l.listing_id,
    l.source,
    l.url,
    l.title,
    l.description,
    l.category,
    l.property_type,
    l.transaction_type,
    l.price,
    l.price_per_sqm,
    l.area_sqm,
    l.bedrooms,
    l.bathrooms,
    l.num_floors,
    l.direction,
    l.direction_code,
    l.legal_status,
    l.legal_status_code,
    l.furniture,
    l.address_raw,
    l.ward_code,
    l.district,
    l.ward,
    COALESCE(l.lat, c.lat) as lat,
    COALESCE(l.lng, c.lng) as lng,
    l.account_id,
    l.account_name,
    l.phone,
    COALESCE(l.is_broker, FALSE) as is_broker,
    l.images,
    l.posted_at,
    l.scraped_at,
    l.is_active
FROM {{ ref('stg_listings') }} l
LEFT JOIN {{ source('raw', 'geocode_cache') }} c ON l.address_raw = c.address_raw
